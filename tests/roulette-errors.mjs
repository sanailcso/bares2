import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../assets/app.js',import.meta.url),'utf8');
const start=source.indexOf('  function rouletteErrorText('),end=source.indexOf('  function renderBet(',start);
const scope={SB_ON:true,SB_SECURE:true,currentUser:'test2',_CRED:{t:'fixture-token'},sbRpc:async()=>{throw Object.assign(new Error('sensitive SQL detail fixture-token'),{status:500,code:'57014'});}};
vm.createContext(scope);vm.runInContext(source.slice(start,end),scope);
const response=await scope.secureBet(100);
assert.equal(response.error,'request');assert.equal(response.status,500);assert.equal(response.code,'57014');
assert.match(scope.rouletteErrorText(response),/HTTP 500 · 57014/);
assert.doesNotMatch(scope.rouletteErrorText(response),/SQL|fixture-token/);
assert.match(scope.rouletteErrorText({error:'odds'}),/configuración/);
assert.match(scope.rouletteErrorText({error:'stake'}),/límites/);
assert.match(scope.rouletteErrorText({error:'limit',betSpins:0}),/No tienes tiradas/);
assert.doesNotMatch(scope.rouletteErrorText({error:'limit',betSpins:1}),/No tienes tiradas/);
scope.sbRpc=async()=>{throw new TypeError('Failed to fetch');};
const offline=await scope.secureBet(100);assert.equal(offline.error,'request');
assert.doesNotMatch(scope.rouletteErrorText(offline),/HTTP|SQL|undefined/);
console.log('Roulette errors: preserve HTTP diagnostics, distinguish business failures, redact internals');
