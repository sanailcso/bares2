import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const scope = { window: {} };
vm.runInNewContext(fs.readFileSync(new URL('../assets/reward-images.js', import.meta.url), 'utf8'), scope);
const photos = scope.window.TkRewardImages;
const rewards = [{ name: 'Mochila de viaje' }, { name: 'Gorra Tiki Taka', image: null }, { name: 'Llavero premium', image: 'data:image/webp;base64,custom' }];
photos.migrate(rewards);
assert.equal(rewards[0].image, './img/club-rewards-sheet.jpg#reward-0');
assert.equal(rewards[1].image, null, 'Removing a photo must remain effective after reload');
assert.equal(rewards[2].image, 'data:image/webp;base64,custom', 'Preserve admin uploads');
rewards[0].name = 'Mochila nueva';
photos.migrate(rewards);
assert.equal(rewards[0].image, './img/club-rewards-sheet.jpg#reward-0', 'Renaming keeps the selected photo');
const persisted = JSON.parse(JSON.stringify(rewards));
photos.migrate(persisted);
assert.deepEqual(persisted, rewards, 'Image choices survive the saved config round trip');
assert.match(photos.markup(rewards[0], false), /viewBox="0 0 443.5 443.5"/);
assert.match(photos.markup({name:'TV',image:'./img/club-rewards-sheet.jpg#reward-4'}, false), /viewBox="0 443.5 443.5 443.5"/);
assert.match(photos.markup({name:'"<TV>',image:'photo.jpg?a=1&b=2'}, false), /alt="&quot;&lt;TV&gt;"/);
assert.equal(photos.markup(rewards[1], false), '');
assert.equal((photos.options().match(/<option /g) || []).length, 12);
const app = fs.readFileSync(new URL('../assets/app.js', import.meta.url), 'utf8');
assert.match(app, /TkRewardImages\.markup\(r, false\)/, 'Admin renders the shared image value');
assert.match(app, /TkRewardImages\.markup\(it, true\)/, 'Client renders the shared image value');
assert.match(app, /DRAFT\.rewards\[i\]\.image=inp\.value/);
console.log('Imágenes compartidas del catálogo: comprobaciones superadas');
